"use strict";
const assert = require("node:assert/strict");
const ClassroomDemo = require("./classroom.js");
const demo = new ClassroomDemo();
assert.deepEqual(demo.classesFor("教师T1").map((item) => item.id), ["C1"]);
const rows = demo.rows("教师T1", "C1");
assert.deepEqual(rows.map((item) => item.groupId), ["G1", "G2", "G3"]);
assert.equal(rows[2].submitted, false);
assert.equal(demo.work("教师T1", "W2").groupId, "G2");
assert.throws(() => demo.rows("教师T2", "C1"), /拒绝/);
assert.throws(() => demo.work("教师T2", "W1"), /拒绝/);
assert.throws(() => demo.work("学生G2", "W1"), /拒绝/);
assert.deepEqual(demo.ownWorks("学生G2", "C1").map((item) => item.id), ["W2"]);
const before = JSON.stringify(demo.data);
assert.throws(() => demo.decide("学生G1", "W1", "I1", "已确认", "无权"), /拒绝/);
assert.throws(() => demo.decide("教师T2", "W1", "I1", "已确认", "跨班"), /拒绝/);
assert.throws(() => demo.decide("教师T1", "W1", "I1", "已确认", "  "), /理由/);
assert.equal(JSON.stringify(demo.data), before);
demo.decide("教师T1", "W1", "I1", "已确认", "示例缺少可验证的时限");
assert.equal(demo.work("教师T1", "W1").issues[0].status, "已确认");
assert.equal(demo.work("教师T1", "W2").issues[0].status, "待教师复核");
assert.equal(demo.log[0].classId, "C1");
assert.equal(demo.log[0].version, "v1");
const forged = new ClassroomDemo();
forged.data.works[0].classId = "C2";
assert.throws(() => forged.work("教师T2", "W1"), /归属/);
assert.throws(() => forged.rows("教师T1", "C1"), /归属/);
assert.equal(demo.rows("教师T1", "C1")[0].pending, 0);
console.log("通过：教师查看负责教学班全部小组、未提交状态、同班多组访问、跨班/跨组拒绝、学生不能代复核、作品归属一致及复核记录相互隔离。");
console.log("范围：内存数据与前端模拟；不证明服务端授权或真实模型审查通过。");
